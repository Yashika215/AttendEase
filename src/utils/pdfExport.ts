import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { AttendanceRecord } from '../types';

export interface PdfReportOptions {
  title: string;
  subtitle?: string;
  generatedBy?: string;
  collegeName?: string;
  filename?: string;
}

export function exportAttendanceToPdf(records: AttendanceRecord[], options: PdfReportOptions) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  const college = options.collegeName || 'JG University — AttendEase';

  doc.setFillColor(20, 33, 61);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 82, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.text(options.title, 40, 36);

  doc.setFontSize(10);
  doc.setTextColor(191, 219, 254);
  doc.text(`${college}${options.subtitle ? `  ·  ${options.subtitle}` : ''}`, 40, 56);

  const presentCount = records.filter((r) => r.status === 'present').length;
  const absentCount = records.filter((r) => r.status === 'absent').length;
  const rate = records.length > 0 ? Math.round((presentCount / records.length) * 100) : 0;

  doc.setTextColor(30, 41, 59);
  doc.setFontSize(10);
  doc.text(
    `Total Records: ${records.length}   |   Present: ${presentCount}   |   Absent: ${absentCount}   |   Attendance Rate: ${rate}%`,
    40,
    106
  );

  if (options.generatedBy) {
    doc.setTextColor(100, 116, 139);
    doc.setFontSize(9);
    doc.text(
      `Generated by: ${options.generatedBy} on ${new Date().toLocaleString()}`,
      40,
      122
    );
  }

  autoTable(doc, {
    startY: 138,
    head: [['Date', 'Student Name', 'Student ID', 'Subject', 'Method', 'Status']],
    body: records.map((r) => [
      r.date,
      r.studentName,
      r.studentId,
      r.classCode ? `${r.classCode} · ${r.className}` : r.className,
      (r.method || 'manual').toUpperCase(),
      r.status.toUpperCase()
    ]),
    styles: { fontSize: 9, cellPadding: 6 },
    headStyles: { fillColor: [37, 99, 235], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [248, 250, 252] }
  });

  doc.save(options.filename || `attendease-report-${new Date().toISOString().slice(0, 10)}.pdf`);
}
